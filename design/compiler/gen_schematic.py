"""Write design/compiler/cells/<cell>.sch (xschem) for every periphery cell.

Usage: python3 -I design/compiler/gen_schematic.py [--check]
Topologies and sizes come from cells.py + sizing.json; netlists are produced by
`klt netlist` (never raw xschem) via netlists.py. --check exits 3 if a committed
schematic differs from what this generator would write.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))  # -I drops the script dir
import cells  # noqa: E402

here = pathlib.Path(__file__).resolve().parent
out_dir = here / "cells"


def render(name, ports, devs):
    out = [f"""v {{xschem version=3.4.5 file_version=1.2
* {name} -- sky130 SRAM compiler periphery cell (issue #26)
* Generated by design/compiler/gen_schematic.py from cells.py + sizing.json;
* do not edit by hand. Ports: {' '.join(ports)}.
* Devices are ordinary 1.8 V logic models (nfet_01v8 / pfet_01v8).
}}
G {{}}
K {{}}
V {{}}
S {{}}
E {{}}"""]
    n = [0]

    def pin(x, y, net):
        n[0] += 1
        out.append(f"C {{devices/lab_pin.sym}} {x} {y} 0 0 {{name=l{n[0]} lab={net}}}")

    def wire(x0, y0, x1, y1):
        out.append(f"N {x0} {y0} {x1} {y1} {{}}")

    for i, (dname, role, d, g, s, b) in enumerate(devs):
        model, w, l = cells.device(role)
        x, y = 150 * (i % 8), 250 * (i // 8)
        # The PDK symbols derive ad/as/pd/ps/nrd/nrs with expr(); older xschem leaves
        # that unevaluated, so the nf=1 values are written out (same as design/bitcell).
        geo = (f"ad={w * 0.29:.4g} as={w * 0.29:.4g} pd={2 * (w + 0.29):.4g} ps={2 * (w + 0.29):.4g} "
               f"nrd={0.29 / w:.4g} nrs={0.29 / w:.4g} sa=0 sb=0 sd=0")
        out.append(f"C {{sky130_fd_pr/{model}.sym}} {x} {y} 0 0 "
                   f"{{name={dname} L={l} W={w} nf=1 mult=1 {geo} model={model} spiceprefix=X}}")
        pm = model.startswith("pfet")
        dy, sy = (30, -30) if pm else (-30, 30)
        wire(x + 20, y + dy, x + 20, y + dy * 5 // 3)
        pin(x + 20, y + dy * 5 // 3, d)
        wire(x + 20, y + sy, x + 20, y + sy * 5 // 3)
        pin(x + 20, y + sy * 5 // 3, s)
        wire(x - 20, y, x - 40, y)
        pin(x - 40, y, g)
        wire(x + 20, y, x + 40, y)
        pin(x + 40, y, b)
    for k, p in enumerate(ports):
        out.append(f"C {{devices/iopin.sym}} {-150} {50 * k} 0 0 {{name=p{k} lab={p}}}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    drift = []
    for name, (ports, devs) in sorted(cells.CELLS.items()):
        path = out_dir / f"{name}.sch"
        text = render(name, ports, devs)
        if check:
            if not path.exists() or path.read_text() != text:
                drift.append(path.name)
        else:
            out_dir.mkdir(exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(here.parent.parent))
    if drift:
        print("drifted:", " ".join(drift), file=sys.stderr)
        sys.exit(3)


main()
