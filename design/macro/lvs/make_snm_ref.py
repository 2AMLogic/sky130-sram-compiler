"""Write the LVS reference netlist of the SNM half-cell column top (gen_layout.py --snm-halfcell).

Usage: python3 -I design/macro/lvs/make_snm_ref.py [--check]
  writes design/macro/lvs/sram_snm_halfcell_col64.spice, or with --check exits 3 if the committed
  file differs.

Provenance: nothing is typed in here. bitcell_6t and sram_precharge are taken verbatim from the
committed macro netlist (design/compiler/macro/sram_256x32_m4.spice), and the half-cell's three
devices are that bitcell's XMPL / XMNL / XMAL lines with the cross-coupled nets cut: the shared gate
is the free input IN and the drain node Q is the free output OUT (the decoupled half cell of
sim/column/lib/make_column_tb.py::snm_tb(mode, pair=False)). Top = the half-cell, 63 bitcell_6t
and one sram_precharge on one bit line, the DC fixture's structure and not the closed-loop cell.
Ports: BL0 BLB0 IN OUT WL0 (half-cell word line) WL1..WL63 (the background rows') PCHB VDD VSS.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
MACRO = ROOT / "design/compiler/macro/sram_256x32_m4.spice"
OUT = ROOT / "design/macro/lvs/sram_snm_halfcell_col64.spice"
TOP, ROWS = "sram_snm_halfcell_col64", 64


def subckt(text, name):
    m = re.search(rf"^\.subckt {name} .*?^\.ends\n", text, re.S | re.M)
    if not m:
        sys.exit(f"make_snm_ref: subckt {name} not found in {MACRO}")
    return m.group(0)


def render():
    text = MACRO.read_text()
    bit, pre = subckt(text, "bitcell_6t"), subckt(text, "sram_precharge")
    dev = {}
    for inst in ("XMPL", "XMNL", "XMAL"):
        m = re.search(rf"^{inst} (\S+) (\S+) (\S+) (\S+) (sky130_fd_pr__.*)$", bit, re.M)
        if not m:
            sys.exit(f"make_snm_ref: {inst} not found in bitcell_6t")
        dev[inst] = m.groups()
    # nets of the cut half cell: pu/pd gate = IN, drain = OUT, access between BL and OUT
    (_, _, _, _, pu), (_, _, _, _, pd), (_, _, _, _, ax) = dev["XMPL"], dev["XMNL"], dev["XMAL"]
    half = "\n".join([
        ".subckt snm_halfcell BL WL IN OUT VDD VSS",
        "*.iopin BL", "*.iopin WL", "*.iopin IN", "*.iopin OUT", "*.iopin VDD", "*.iopin VSS",
        f"XMPL OUT IN VDD VDD {pu}",
        f"XMNL OUT IN VSS VSS {pd}",
        f"XMAL BL WL OUT VSS {ax}",
        ".ends", ""])
    wls = " ".join(f"WL{r}" for r in range(ROWS))
    top = [f".subckt {TOP} BL0 BLB0 IN OUT PCHB VDD VSS {wls}",
           "XH0_0 BL0 WL0 IN OUT VDD VSS snm_halfcell"]
    top += [f"XC{r}_0 BL0 BLB0 WL{r} VDD VSS bitcell_6t" for r in range(1, ROWS)]
    top += ["XPCH0 BL0 BLB0 PCHB VDD sram_precharge", ".ends", ""]
    return ("** SNM half-cell column top: LVS reference for gen_layout.py --snm-halfcell\n"
            "** generated by design/macro/lvs/make_snm_ref.py from the committed macro netlist; do not edit by hand\n"
            + bit + pre + half + "\n".join(top))


if __name__ == "__main__":
    text = render()
    if sys.argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"make_snm_ref: {OUT} drifted from the generator", file=sys.stderr)
            sys.exit(3)
    elif sys.argv[1:] == []:
        OUT.write_text(text)
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
