#!/usr/bin/env bash
# layout/control/sdf/run_sta_sdf.sh -- regenerate the per-corner post-route
# SDFs that `klt place-and-route` cannot write itself. run_pnr.sh's flow
# writes one SDF at its own P&R corner (tt_025C_1v80, committed as
# sdf/sram_ctrl.tt_025C_1v80.sdf); re-running the flow at another corner
# would re-place and re-route. `klt sta` instead analyses the SAME committed
# routed DEF (../sram_ctrl.def) and SPEF (../sram_ctrl.spef) and writes one
# SDF per requested corner (sta.request.json; today the worst-setup corner
# ss_n40C_1v28 the P&R response reports).
#
# Usage: layout/control/sdf/run_sta_sdf.sh    (rewrites the committed SDFs)
# Needs klt (repo pin: klayout-tools 0.9.0), the openroad wrapper and the
# PDK pinned in sim/pdk.json. OpenSTA stamps a (DATE ...) header line into
# each SDF, so regenerated bytes differ from the committed ones while the
# delays do not; the SDF-annotated runs consume the file by path, never by
# hash.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
cd "$repo"
dir=layout/control/sdf
scratch=sim/build/sta-sdf

for t in klt openroad jq; do
  command -v "$t" >/dev/null || { echo "run_sta_sdf.sh: TOOL_MISSING: $t not on PATH" >&2; exit 1; }
done
# shellcheck source=../../../sim/env.sh
source sim/env.sh >/dev/null || { echo "run_sta_sdf.sh: PDK environment refused (see env.sh error above)" >&2; exit 1; }

mkdir -p "$scratch"
klt sta "$dir/sta.request.json" --pdk "$PDK" --pdk-root "$PDK_ROOT" --format json \
  > "$scratch/sta.response.json"
jq -e '.status == "ok" and ([.corners[].sdf.path] | all(type == "string"))' \
  "$scratch/sta.response.json" >/dev/null \
  || { echo "run_sta_sdf.sh: klt sta did not report an SDF for every requested corner" >&2; exit 1; }

for corner in $(jq -r '.pdk.corners[]' "$dir/sta.request.json"); do
  src="$dir/.klt/sta/sram_ctrl.$corner.sdf"
  [[ -s "$src" ]] || { echo "run_sta_sdf.sh: $src missing or empty" >&2; exit 1; }
  cp "$src" "$dir/sram_ctrl.$corner.sdf"
  echo "run_sta_sdf.sh: wrote $dir/sram_ctrl.$corner.sdf"
done
