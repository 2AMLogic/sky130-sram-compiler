"""`klt erc` supply spec generator: (words, bits, mux) -> the macro's ERC spec (T1 item 11).

Usage (needs klayout's python module, because the tap-row positions come from gen_layout.build()):
  uv run --no-project --with klayout python -I design/compiler/gen_erc_spec.py macro WORDS BITS MUX \
      [-o OUT.json] [--check OUT.json]
  uv run --no-project --with klayout python -I design/compiler/gen_erc_spec.py control [-o OUT.json] [--check OUT.json]
--check exits 3 when the committed spec differs from a fresh one.

One code path for every size. The stackup and vias are the layout generator's own layer table
(gen_layout.LAYERS), the supplies are `VDD`/`VSS` (the names the layout labels carry), and the tie
boxes are computed from `gen_layout.ArrayGeom` (the p-substrate strap rows) and the column-mux cell
(its VSS bulk tap) at the same pitch the layout uses, so the spec cannot drift from the layout by hand.

What the spec asserts, and what it does not:
  * Each supply is one labelled island (`nets[].islands` default 1).
  * `roles`: VSS owns met1 and VDD owns met2 inside the ARRAY box (the vertical VSS / VDD columns);
    both own met3 and met4 everywhere (the supply buses and rings). Any unlabelled conductor on an
    owned role is `erc.unlabelled_conductor`, so a severed rail piece is caught even without a label.
    Outside the array box, met1 / met2 carry the periphery's internal signal nets (sense amp latch,
    write driver), which the layout does not label, so that region is carved out with
    `unlabelled_allowed_boxes`. Periphery rails on met1 / met2 are therefore NOT measured for
    severing; they are only proven reachable where a label sits on them.
  * `ties[]`: every drawn nwell polygon must hold an n-tap on VDD (checked everywhere, array and
    periphery); the p-substrate straps and the column-mux bulk taps are asserted with `well_boxes`
    (the substrate has no drawn layer) and must each reach VSS. Other periphery p-taps (the
    row-decoder and control cells) are not asserted: the report's `well_assertion_coverage` says how
    much drawn tap area lies outside the asserted boxes.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))  # -I drops the script dir

NSDM, PSDM = "93/44", "94/20"
TAP_BOX = 0.5   # um: half-width of the box asserted around one column-mux bulk tap


def _ly(name):
    import gen_layout as gl
    return "%d/%d" % gl.LAYERS[name]


def _stackup():
    """poly (the gate role), li, met1..met4 and their vias, from the layout generator's layer table."""
    import gen_layout as gl  # noqa: F401  (imported by _ly)
    st = [{"name": "poly", "layer": _ly("poly"), "role": "gate"},
          {"name": "li", "layer": _ly("li"), "label_layer": _ly("li_lbl")}]
    for n in (1, 2, 3, 4):
        st.append({"name": f"met{n}", "layer": _ly(f"m{n}"), "label_layer": _ly(f"m{n}_lbl")})
    vias = [{"name": "licon", "layer": _ly("licon"), "between": ["poly", "li"]},
            {"name": "mcon", "layer": _ly("mcon"), "between": ["li", "met1"]},
            {"name": "via", "layer": _ly("via"), "between": ["met1", "met2"]},
            {"name": "via2", "layer": _ly("via2"), "between": ["met2", "met3"]},
            {"name": "via3", "layer": _ly("via3"), "between": ["met3", "met4"]}]
    return st, vias


def _r(v):
    return round(v, 3)


def macro_spec(words, bits, mux):
    import gen_layout as gl
    ly, T, env = gl.build(words, bits, mux)
    ag, hcm = env["ag"], env["hcm"]
    bb = T.cell.dbbox()
    W, H = ag.width, ag.height
    stackup, vias = _stackup()
    # periphery slabs around the array: met1 / met2 unlabelled signal conductor is expected there
    periphery = [[_r(bb.left), _r(bb.bottom), 0, _r(bb.top)], [_r(W), _r(bb.bottom), _r(bb.right), _r(bb.top)],
                 [0, _r(bb.bottom), _r(W), 0], [0, _r(H), _r(W), _r(bb.top)]]
    straps = [[0, _r(ag.strap_y(i)), _r(W), _r(ag.strap_y(i) + gl.STRAP_H)] for i in range(len(ag.B))]
    cm_taps = []
    for m in range(mux):
        for b in range(bits):
            x = m * gl.BC_W + b * mux * gl.BC_W + gl.VSS_XS[0]
            y = -hcm + 1.40                      # cell_colmux's ytap
            cm_taps.append([_r(x - TAP_BOX), _r(y - TAP_BOX), _r(x + TAP_BOX), _r(y + TAP_BOX)])
    cm_taps.sort()
    return {
        "_comment": [f"klt erc supply spec for sram_{words}x{bits}_m{mux}, generated by "
                     "design/compiler/gen_erc_spec.py; do not edit by hand."],
        "stackup": stackup,
        "vias": vias,
        "nets": [
            {"name": "VDD", "kind": "supply", "roles": ["met2", "met3", "met4"],
             "unlabelled_allowed_boxes": periphery},
            {"name": "VSS", "kind": "supply", "roles": ["met1", "met3", "met4"],
             "unlabelled_allowed_boxes": periphery},
        ],
        "ties": [
            {"name": "nwell_tie", "well_layer": _ly("nwell"), "tap_layer": _ly("tap"),
             "tap_requires": [NSDM], "tap_is_dedicated": True, "connect_to": "li", "net": "VDD"},
            {"name": "psub_array_straps", "well_layer": None, "well_boxes": straps,
             "tap_layer": _ly("tap"), "tap_requires": [PSDM], "tap_is_dedicated": True,
             "connect_to": "li", "net": "VSS"},
            {"name": "psub_colmux_taps", "well_layer": None, "well_boxes": cm_taps,
             "tap_layer": _ly("tap"), "tap_requires": [PSDM], "tap_is_dedicated": True,
             "connect_to": "li", "net": "VSS"},
        ],
    }


def control_spec():
    """The routed control block (sky130_fd_sc_hd cells): cell pins VPWR/VGND, top met5 pins VDD/VSS.
    met5 is the P&R response's third strap layer, so the stackup reaches it."""
    stackup, vias = _stackup()
    stackup.append({"name": "met5", "layer": "72/20", "label_layer": "72/5"})
    vias.append({"name": "via4", "layer": "71/44", "between": ["met4", "met5"]})
    return {
        "_comment": ["klt erc supply spec for the routed control block (layout/control/control.gds), "
                     "generated by design/compiler/gen_erc_spec.py; do not edit by hand. The cells label "
                     "their rails VPWR/VGND, the PDN straps VDD/VSS (the response's power_net/ground_net)."],
        "stackup": stackup,
        "vias": vias,
        "nets": [
            {"name": "VDD", "kind": "supply"},
            {"name": "VPWR", "kind": "supply", "same_net_as": "VDD"},
            {"name": "VSS", "kind": "supply"},
            {"name": "VGND", "kind": "supply", "same_net_as": "VSS"},
        ],
        "ties": [
            {"name": "nwell_tie", "well_layer": "64/20", "tap_layer": "65/44", "tap_requires": [NSDM],
             "tap_is_dedicated": True, "connect_to": "li", "net": "VPWR"},
        ],
    }


def render(spec):
    return json.dumps(spec, indent=1) + "\n"


def main(argv):
    args = argv[1:]
    out = check = None
    for flag in ("-o", "--check"):
        if flag in args:
            i = args.index(flag)
            val = args[i + 1]
            del args[i:i + 2]
            if flag == "-o":
                out = val
            else:
                check = val
    try:
        if args[:1] == ["macro"] and len(args) == 4:
            import sram_compile as sc
            words, bits, mux = (int(a) for a in args[1:])
            try:
                spec = macro_spec(words, bits, mux)
            except (sc.RangeError, ValueError) as e:
                print(f"gen_erc_spec: error: {e}", file=sys.stderr)
                return 1
        elif args == ["control"]:
            spec = control_spec()
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except ImportError as e:  # both specs read the layer table from gen_layout, which needs klayout
        print(f"gen_erc_spec: TOOL_MISSING: {e}", file=sys.stderr)
        return 1
    text = render(spec)
    if out:
        pathlib.Path(out).write_text(text)
    if check:
        p = pathlib.Path(check)
        if not p.exists() or p.read_text() != text:
            print(f"gen_erc_spec: {check} drifted from the generator", file=sys.stderr)
            return 3
    if not out and not check:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
